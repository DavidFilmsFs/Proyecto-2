const CLAVE_ALMACENAMIENTO = "personajes-ninjago";
const elementos = {
    lista: document.querySelector("#listaPersonajes"),
    plantilla: document.querySelector("#plantillaPersonaje"),
    busqueda: document.querySelector("#buscarPersonaje"),
    contador: document.querySelector("#contadorPersonajes"),
    vacio: document.querySelector("#estadoVacio"),
    dialogo: document.querySelector("#dialogoPersonaje"),
    formulario: document.querySelector("#formularioPersonaje")
};
const campos = ["Nombre", "Poder_elemental", "Origen", "Padres", "descripcion", "primera_aparicion", "imagen"];
const obligatorios = ["Nombre", "Poder_elemental", "Origen"];
let idEnEdicion = null;

function cargarPersonajes() {
    try {
        const guardados = JSON.parse(localStorage.getItem(CLAVE_ALMACENAMIENTO));
        const lista = Array.isArray(guardados) ? guardados : personajesIniciales;
        return lista.map(personaje => ({
            id: personaje.id,
            Nombre: personaje.Nombre ?? personaje.nombre ?? "",
            Poder_elemental: personaje.Poder_elemental ?? personaje["Poder Elemental"] ?? "",
            Origen: personaje.Origen ?? personaje.origen ?? "",
            Padres: personaje.Padres ?? "",
            descripcion: personaje.descripcion ?? "",
            primera_aparicion: personaje.primera_aparicion ?? "",
            imagen: personaje.imagen ?? ""
        })).filter(personaje => personaje.Nombre);
    } catch {
        return personajesIniciales;
    }
}

function guardarPersonajes(lista = personajes) {
    try {
        localStorage.setItem(CLAVE_ALMACENAMIENTO, JSON.stringify(lista));
        return true;
    } catch {
        alert("No se pudieron guardar los cambios.");
        return false;
    }
}

function buscarPersonajes(consulta) {
    let termino = consulta.trim().normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
    let resultados = [];

    while (termino && resultados.length === 0) {
        resultados = personajes.filter(personaje =>
            `${personaje.Nombre} ${personaje.Poder_elemental}`
                .normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().includes(termino)
        );
        if (resultados.length === 0) termino = termino.slice(0, -1);
    }

    return resultados.length ? resultados : personajes;
}

function renderizarGrid() {
    const filtrados = buscarPersonajes(elementos.busqueda.value);

    elementos.lista.replaceChildren();
    filtrados.forEach(personaje => {
        const tarjeta = elementos.plantilla.content.cloneNode(true);
        const tarjetaCard = tarjeta.querySelector(".card");
        const detalles = tarjeta.querySelector(".card-details");
        const botonResumen = tarjeta.querySelector(".card-summary");
        const imagen = tarjeta.querySelector(".imagen-personaje");
        const textos = {
            ".nombre": personaje.Nombre,
            ".poder": personaje.Poder_elemental,
            ".origen": personaje.Origen,
            ".padres": personaje.Padres,
            ".descripcion": personaje.descripcion,
            ".aparicion": personaje.primera_aparicion
        };

        tarjetaCard.dataset.id = personaje.id;
        detalles.id = `detalles-${personaje.id}`;
        botonResumen.setAttribute("aria-controls", detalles.id);
        Object.entries(textos).forEach(([selector, texto]) => {
            tarjeta.querySelector(selector).textContent = texto || (selector === ".descripcion" ? "Sin descripción" : "Sin datos");
        });
        imagen.alt = `Imagen de ${personaje.Nombre}`;
        if (personaje.imagen) {
            imagen.src = personaje.imagen;
            imagen.onerror = () => imagen.hidden = true;
        } else {
            imagen.hidden = true;
        }
        elementos.lista.appendChild(tarjeta);
    });

    elementos.contador.textContent = `Mostrando ${filtrados.length} de ${personajes.length} personajes`;
    elementos.vacio.hidden = filtrados.length > 0;
}

function abrirDialogo(personaje = {}) {
    idEnEdicion = personaje.id ?? null;
    elementos.formulario.reset();
    campos.forEach(campo => elementos.formulario.elements[campo].value = personaje[campo] ?? "");
    document.querySelector("#tituloDialogoPersonaje").textContent = idEnEdicion ? "Editar personaje" : "Agregar personaje";
    elementos.dialogo.showModal();
}

function guardarFormulario(evento) {
    evento.preventDefault();
    const datos = Object.fromEntries(campos.map(campo => [campo, elementos.formulario.elements[campo].value.trim()]));
    if (obligatorios.some(campo => !datos[campo])) {
        alert("Completa los campos obligatorios.");
        return;
    }

    const personaje = { ...datos, id: idEnEdicion ?? `N${Date.now()}` };
    const actualizados = idEnEdicion
        ? personajes.map(item => item.id === idEnEdicion ? personaje : item)
        : [...personajes, personaje];
    if (!guardarPersonajes(actualizados)) return;

    personajes = actualizados;
    elementos.dialogo.close();
    elementos.busqueda.value = "";
    renderizarGrid();
}

elementos.lista.addEventListener("click", evento => {
    const boton = evento.target.closest("button");
    const tarjeta = boton?.closest(".card");
    if (!tarjeta) return;

    const personaje = personajes.find(item => item.id === tarjeta.dataset.id);
    if (boton.matches(".card-summary")) {
        const detalles = tarjeta.querySelector(".card-details");
        detalles.hidden = !detalles.hidden;
        boton.setAttribute("aria-expanded", String(!detalles.hidden));
    } else if (boton.matches(".boton-editar")) {
        abrirDialogo(personaje);
    } else if (boton.matches(".boton-eliminar") && confirm(`¿Eliminar a ${personaje.Nombre}?`)) {
        const actualizados = personajes.filter(item => item.id !== personaje.id);
        if (guardarPersonajes(actualizados)) {
            personajes = actualizados;
            renderizarGrid();
        }
    }
});

document.querySelector("#agregarPersonaje").addEventListener("click", () => abrirDialogo());
document.querySelector("#cerrarDialogo").addEventListener("click", () => elementos.dialogo.close());
document.querySelector("#cancelarDialogo").addEventListener("click", () => elementos.dialogo.close());
elementos.busqueda.addEventListener("input", renderizarGrid);
elementos.formulario.addEventListener("submit", guardarFormulario);
elementos.dialogo.addEventListener("click", evento => {
    if (evento.target === elementos.dialogo) elementos.dialogo.close();
});

let personajes = cargarPersonajes();
renderizarGrid();





